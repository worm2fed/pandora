def _journal(root: Path, *args: str) -> str:
    proc = run_journal(["--db", root / "shipgate.db", *args], cwd=root)
    if proc.returncode != 0:
        raise AssertionError(
            f"journal.py {' '.join(args)} exited {proc.returncode}: {proc.stderr}"
        )
    return proc.stdout


def _set_times(root: Path) -> dict:
    """Stamp every event with a time the test chooses; return real -> placeholder."""
    now = datetime.now(timezone.utc).replace(microsecond=0)
    conn = sqlite3.connect(str(root / "shipgate.db"))
    try:
        rows = conn.execute("SELECT seq, stream FROM events ORDER BY seq").fetchall()
        last = rows[-1][0]
        stamps = {}
        for seq, stream in rows:
            age = timedelta(minutes=last - seq + 1)
            if stream == DORMANT:
                age += DORMANT_AGE
            real = (now - age).isoformat()
            conn.execute("UPDATE events SET ts = ? WHERE seq = ?", (real, seq))
            stamps[real] = (GOLDEN_NOW - age).isoformat()
        conn.commit()
    finally:
        conn.close()
    return stamps


def _normalise(value, stamps: dict, roots: list):
    if isinstance(value, dict):
        return {key: _normalise(item, stamps, roots) for key, item in value.items()}
    if isinstance(value, list):
        return [_normalise(item, stamps, roots) for item in value]
    if isinstance(value, str):
        if value in stamps:
            return stamps[value]
        for root in roots:
            value = value.replace(root, "<project>")
    return value


def build_golden() -> tuple:
    """The scripted journal's ``status`` and ``position`` output, normalised, and the
    placeholders the event times became."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        for relpath, text in FILES.items():
            path = root / relpath
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        _journal(root, "init")
        for stream, event_type, data, actor in SCRIPT:
            argv = ["append", "--stream", stream, "--type", event_type,
                    "--data", json.dumps(data)]
            if actor is not None:
                argv += ["--actor", actor]
            _journal(root, *argv)
        stamps = _set_times(root)
        roots = sorted({str(root), str(root.resolve())}, key=len, reverse=True)
        status = {
            name: _normalise(json.loads(_journal(root, "status", "--json", *flags)),
                             stamps, roots)
            for name, flags in STATUS_RUNS.items()
        }
        position = {
            name: _normalise(
                json.loads(_journal(root, "position", "--stream", stream, "--json")),
                stamps, roots,
            )
            for name, stream in POSITION_RUNS.items()
        }
    return status, position, set(stamps.values())


def render_golden(status: dict, position: dict) -> str:
    def literal(value) -> str:
        return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False)

    return "\n".join([
        HEADER,
        f"// Regenerate: {REGEN_ENV}=1 python3 -m unittest discover -s shipgate/tests "
        "-k HudContract",
        "// journal.py's own output for a scripted journal (shipgate ADR 0009). Event",
        "// times are placeholders at their real distance from GOLDEN_NOW.",
        "",
        f"export const GOLDEN_NOW = '{GOLDEN_NOW.isoformat()}'",
        "",
        "/** `status --json`, by scenario (the flags are in test_hud_contract.py). */",
        f"export const STATUS_GOLDEN = {literal(status)} as const",
        "",
        "/** `position --stream <s> --json`, by scenario. */",
        f"export const POSITION_GOLDEN = {literal(position)} as const",
        "",
    ])


@unittest.skipUnless(HUD.is_dir(), "shipgate-hud is not in this checkout")
class TestHudContract(unittest.TestCase):
    """journal.py's JSON and the HUD's golden file are one contract."""

    @classmethod
    def setUpClass(cls):
        cls.status, cls.position, cls.placeholders = build_golden()

    def test_the_golden_file_is_journal_py_output(self):
        actual = render_golden(self.status, self.position)
        if os.environ.get(REGEN_ENV) == "1":
            GOLDEN.write_text(actual, encoding="utf-8")
            return
        if not GOLDEN.is_file():
            self.fail(f"{GOLDEN} is missing — generate it with {REGEN_ENV}=1")
        expected = GOLDEN.read_text(encoding="utf-8")
        if actual == expected:
            return
        diff = "".join(difflib.unified_diff(
            expected.splitlines(True), actual.splitlines(True),
            "fixtures.journal.ts (committed)", "journal.py (now)", n=2,
        ))
        self.fail(
            "journal.py's JSON no longer matches the HUD's golden file. If the change "
            f"is intended, regenerate it with {REGEN_ENV}=1 and update the HUD's "
            f"decoders to match:\n{diff[:6000]}"
        )

    # The script must keep exercising every field the HUD decodes, or a regenerated
    # golden file would quietly stop covering one.
    def test_the_status_runs_cover_every_binding(self):
        self.assertEqual(self.status["branch"]["branch_match"], FLOW)
        self.assertEqual(self.status["session"]["session_match"], EPIC)
        self.assertIsNone(self.status["session"]["branch_match"])
        self.assertEqual(self.status["nested_one"]["branch_match"], NESTED)
        self.assertEqual(self.status["nested_one"]["nested_matches"], [NESTED])
        self.assertIsNone(self.status["nested_two"]["branch_match"])
        self.assertEqual(self.status["nested_two"]["nested_matches"], [NESTED, FLOW])
        self.assertEqual(self.status["branch"]["nested_matches"], [])
        self.assertEqual(self.status["branch"]["hidden_terminal"], 1)
        lifecycles = {f["stream"]: f["lifecycle"] for f in self.status["all"]["features"]}
        self.assertEqual(lifecycles[DORMANT], "dormant")
        self.assertEqual(lifecycles[DONE], "terminal")
        self.assertEqual(lifecycles[FLOW], "live")
        currents = {f["stream"]: f["current"] for f in self.status["all"]["features"]}
        self.assertIsNone(currents[STARTED])
        self.assertTrue(currents[NAMED]["implied"])

    def test_the_position_runs_cover_every_field(self):
        flow = self.position["flow"]
        self.assertEqual(set(flow["phases"].values()),
                         {"done", "skipped", "current", "revisited", "todo"})
        self.assertEqual(flow["publish"]["kind"], "authorized")
        self.assertEqual(flow["publish"]["by"], "gate-decision")
        self.assertEqual(flow["artifacts"]["worklog_from"], "event")
        self.assertEqual(flow["artifacts"]["prd"], "docs/prd/golden-flow.md")
        self.assertEqual(len(flow["artifacts"]["adrs"]), 2)
        self.assertEqual([t["id"] for t in flow["tasks"]], ["T001", "T002", "T003", "T004"])
        self.assertIn(None, [t["title"] for t in flow["tasks"]])
        self.assertIn(None, [t["last_verify"] for t in flow["tasks"]])
        self.assertEqual(flow["last_verify"]["outcome"], "fail")
        self.assertEqual({d["raised_by"] for d in flow["decisions"]},
                         {"user", "orchestrator"})
        self.assertEqual(flow["verdict"]["verdict"], "not-ready")
        self.assertTrue(flow["verdict"]["criteria"])
        self.assertTrue(flow["verdict"]["dispositions"])
        started = self.position["started"]
        self.assertIsNone(started["current"])
        self.assertIsNone(started["tasks"])
        self.assertIsNone(started["verdict"])
        self.assertEqual(self.position["named"]["artifacts"]["worklog_from"], "name")
        self.assertEqual(self.position["dormant"]["lifecycle"], "dormant")
        self.assertEqual(self.position["done"]["lifecycle"], "terminal")

    def test_no_volatile_value_is_left(self):
        """Every timestamp is a placeholder, and no temp path is printed."""
        text = render_golden(self.status, self.position)
        stamps = set(re.findall(r"\d{4}-\d{2}-\d{2}T[0-9:.]+[+-]\d{2}:\d{2}", text))
        self.assertTrue(stamps)
        self.assertLessEqual(stamps, self.placeholders | {GOLDEN_NOW.isoformat()})
        self.assertNotIn(tempfile.gettempdir(), text)
        self.assertNotIn(str(Path(tempfile.gettempdir()).resolve()), text)


if __name__ == "__main__":
    unittest.main()
