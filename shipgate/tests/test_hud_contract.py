#!/usr/bin/env python3
"""The golden contract between journal.py and shipgate-hud (shipgate ADR 0009).

A scripted journal, built through the CLI, is read back with ``status --json`` and
``position --stream <s> --json``. The output, with its timestamps and the temp path
normalised, must equal ``shipgate-hud/tests/fixtures.journal.ts``, which the HUD's
decoders read in their own tests. A key renamed on either side fails a build.

    SHIPGATE_REGEN_GOLDEN=1 python3 -m unittest discover -s shipgate/tests -k HudContract

writes the file from the current journal.py instead of comparing.

The event times are set by the test, relative to the time it runs: every live stream's
events are minutes old, the dormant stream's ten days. So ``age_days`` and the
lifecycles are stable, and each timestamp maps to one fixed placeholder at the same
distance from ``GOLDEN_NOW``.
"""

